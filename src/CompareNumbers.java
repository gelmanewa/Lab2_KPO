
public class CompareNumbers {

	public static void main(String[] args) {
		// 3 задание сравнение двух чисел
		int num1 = 3;
        int num2 = 10;

        if (num1 > num2) {
            System.out.println("Первое число (" + num1 + ") больше второго (" + num2 + ")");
        } 
        else if (num1 < num2) {
            System.out.println("Первое число (" + num1 + ") меньше второго (" + num2 + ")");
        } else {
            System.out.println("Первое число (" + num1 + ") равно второму (" + num2 + ")");
        }
	}

}
